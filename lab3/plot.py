import numpy as np
import matplotlib.pyplot as plt

fun = np.loadtxt("fun.csv",delimiter=',')
wez = np.loadtxt("wez.csv",delimiter=',')
dp = np.loadtxt("dp.csv",delimiter=',')

plt.figure(figsize=(12,7))
plt.plot(wez[:,0],wez[:,1],label="MES")
plt.plot(wez[:,0],wez[:,2],ls='--',c='k',label="Dokładne")
plt.legend()
plt.xlabel("x")
plt.ylabel("u(x)")
plt.title("Rozwiązanie u(x) w węzłach")
plt.grid(ls=":")
plt.tight_layout()
plt.savefig("wez.png",dpi=150)
plt.close()

plt.figure(figsize=(12,7))
plt.plot(fun[:,0],fun[:,1],label="MES")
plt.plot(fun[:,0],fun[:,2],ls='--',c='k',label="Dokładne")
plt.legend()
plt.xlabel("x")
plt.ylabel("u(x)")
plt.title("Rozwiązanie u(x) poza węzłami")
plt.grid(ls=":")
plt.tight_layout()
plt.savefig("fun.png",dpi=150)
plt.close()

plt.figure(figsize=(12,7))
plt.plot(fun[:,0],fun[:,3],label="Błąd MES")
plt.scatter(wez[:,0],np.zeros(wez[:,0].shape),c='r',label='Węzły')
plt.legend()
plt.xlabel("x")
plt.ylabel("dokl(x)-u(x)")
plt.title("Błąd rozwiąznia MES")
plt.grid(ls=":")
plt.tight_layout()
plt.savefig("deltafun.png",dpi=150)
plt.close()

plt.figure(figsize=(12,7))
plt.plot(dp[:,0],dp[:,1],label=r"$u''(x)$")
plt.plot(dp[:,0],dp[:,2],label=r"$-\rho(x)$")
plt.xlabel("x")
plt.ylabel("y")
plt.title("Porówanie drugiej pochodnej")
plt.grid(ls=":")
plt.legend()
plt.tight_layout()
plt.savefig("dp.png",dpi=150)
plt.close()
